"""Set up this PC for the project: `just setup` (or `uv run scripts/setup.py`).

Installs what building, flashing and talking to the board needs: rustup with the firmware's toolchain and target,
probe-rs, flip-link, cnt, ww and boardmap, and turns on the project's git hooks (`scripts/hooks.py`, chained to the hooks already there). Before
it changes anything it prints its plan, naming every script it fetches from the internet and runs (rustup's and probe-rs's
installers, probe-rs's udev rules file).
Steps that need root or an administrator (system packages, the probe's udev rule, the ST-LINK driver) are printed
for you to run; `--root` runs them too, each shown before it runs. `--check` only reports what is missing and exits
with 1 if anything is (also a CI step); `--skip TOOL` leaves a step out.

Works on Arch, Ubuntu / Debian and Windows (winget); other Linux distributions and macOS get the same steps with
the system packages described instead of a ready command. Python because it runs before Rust is installed: the
prerequisites are just and uv. Generated by embedded_bedrock's firmware template.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import time
import tomllib
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIRMWARE = ROOT / "firmware"

# Tools installed with cargo: (binary, what it is for, `cargo install` arguments)
CARGO_TOOLS = [
    ("flip-link", "linker with stack overflow protection, used by the firmware build", ["flip-link"]),
    ("cnt", "defmt log and event counters of the running firmware (`just cnt`, `cnt tui`)", ["cnt_cli"]),
    (
        "ww",
        "WireWeaver command line: introspect and call any API",
        ["--git", "https://github.com/vhrdtech/wire_weaver", "wire_weaver_cli"],
    ),
    (
        "boardmap",
        "re-draws the board pictures in docs/board/ (`just board`)",
        ["--git", "https://github.com/romixlab/embedded_bedrock", "bedrock_board_cli"],
    ),
]

PROBE_RS_INSTALLER = "https://github.com/probe-rs/probe-rs/releases/latest/download/probe-rs-tools-installer"
RUSTUP_INSTALLER = "https://sh.rustup.rs"
# probe-rs's udev rules (https://probe.rs/files/69-probe-rs.rules), pinned to a commit of its source
PROBE_RS_UDEV = "https://raw.githubusercontent.com/probe-rs/webpage/2770cdb68de046dbcab17806a81b1e76644b2f1c/public/files/69-probe-rs.rules"
UDEV_DIRS = [Path("/etc/udev/rules.d"), Path("/usr/lib/udev/rules.d"), Path("/lib/udev/rules.d")]
# The debug probe: its name and what a udev rules file for it contains
PROBE = ("ST-LINK", ["0483", "374b"])
# Windows driver for the probe: what `pnputil /enum-drivers` shows once it is installed, and how to install it
WINDOWS_DRIVER = (
    "stlink",
    (
        "download STSW-LINK009 from https://www.st.com/en/development-tools/stsw-link009.html, unpack it and run "
        "dpinst_amd64.exe (asks for administrator rights)"
    ),
)


# ---------------------------------------------------------------------------------------------------------------- output


class Style:
    def __init__(self) -> None:
        self.on = sys.stdout.isatty() and not os.environ.get("NO_COLOR")
        if os.name == "nt":
            sys.stdout.reconfigure(encoding="utf-8")  # a pipe would be cp1252, without ✓ and ✗
            if self.on:
                os.system("")  # turns on ANSI escapes in the Windows console

    def _c(self, code: str, s: str) -> str:
        return f"\x1b[{code}m{s}\x1b[0m" if self.on else s

    def ok(self, s: str) -> str:
        return self._c("32", s)

    def bad(self, s: str) -> str:
        return self._c("31", s)

    def warn(self, s: str) -> str:
        return self._c("33", s)

    def bold(self, s: str) -> str:
        return self._c("1", s)

    def dim(self, s: str) -> str:
        return self._c("2", s)


S = Style()


# -------------------------------------------------------------------------------------------------------------- platform


@dataclass
class Platform:
    kind: str  # "arch", "debian", "linux", "macos", "windows"
    name: str
    is_root: bool

    @property
    def sudo(self) -> str:
        return "" if self.is_root else "sudo "


def detect_platform() -> Platform:
    if sys.platform == "win32":
        return Platform("windows", "Windows", False)
    if sys.platform == "darwin":
        return Platform("macos", "macOS", False)
    release: dict[str, str] = {}
    for path in ("/etc/os-release", "/usr/lib/os-release"):
        try:
            for line in Path(path).read_text().splitlines():
                key, sep, value = line.partition("=")
                if sep:
                    release[key] = value.strip().strip('"')
            break
        except OSError:
            continue
    ids = {release.get("ID", "")} | set(release.get("ID_LIKE", "").split())
    name = release.get("PRETTY_NAME", "Linux")
    is_root = os.geteuid() == 0
    if "arch" in ids:
        return Platform("arch", name, is_root)
    if ids & {"debian", "ubuntu"}:
        return Platform("debian", name, is_root)
    return Platform("linux", name, is_root)


# ----------------------------------------------------------------------------------------------------------------- steps


@dataclass
class Status:
    ok: bool
    detail: str = ""


@dataclass
class Step:
    name: str
    check: Callable[[], Status]
    # Without root: a function that installs (returns False on failure). With root: shell commands for the person.
    install: Callable[[], bool] | None = None
    root_commands: list[str] = field(default_factory=list)
    # What to do by hand when there is no command (a download page, a distribution without a known package)
    manual: str = ""
    # A later step cannot work without this one (build tools before cargo install)
    prerequisite: bool = False
    # What it fetches from the internet and runs (an installer script), said in the plan before it runs
    remote: str = ""


def cargo_bin() -> Path:
    return Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "bin"


def which(tool: str) -> str | None:
    """A tool on PATH, or in cargo's bin directory (not on PATH yet in the shell that ran rustup's installer)."""
    found = shutil.which(tool)
    if found:
        return found
    exe = cargo_bin() / (tool + (".exe" if os.name == "nt" else ""))
    return str(exe) if exe.exists() else None


def output(*cmd: str, cwd: Path | None = None) -> str | None:
    """stdout of a command, None when it is missing or fails."""
    exe = which(cmd[0])
    if not exe:
        return None
    try:
        res = subprocess.run([exe, *cmd[1:]], check=False, cwd=cwd, capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return res.stdout if res.returncode == 0 else None


def version_of(tool: str) -> Status:
    out = output(tool, "--version")
    if out is None:
        path = which(tool)  # flip-link has no --version: it runs as the linker
        return Status(True, path) if path else Status(False, "not found")
    return Status(True, out.strip().splitlines()[0] if out.strip() else which(tool) or "")


def run(cmd: list[str], cwd: Path | None = None) -> bool:
    exe = which(cmd[0]) or cmd[0]
    print(S.dim("  $ " + " ".join(cmd)), flush=True)
    try:
        return subprocess.run([exe, *cmd[1:]], check=False, cwd=cwd).returncode == 0
    except OSError as e:
        print(S.bad(f"  {e}"))
        return False


def download(url: str, suffix: str) -> Path:
    print(S.dim(f"  downloading {url}"), flush=True)
    fd, name = tempfile.mkstemp(suffix=suffix)
    with urllib.request.urlopen(url, timeout=60) as resp, os.fdopen(fd, "wb") as f:
        shutil.copyfileobj(resp, f)
    return Path(name)


def add_cargo_bin_to_path() -> None:
    bin_dir = str(cargo_bin())
    if bin_dir not in os.environ.get("PATH", "").split(os.pathsep):
        os.environ["PATH"] = bin_dir + os.pathsep + os.environ.get("PATH", "")


# Toolchain from the firmware's rust-toolchain.toml (the host workspace builds with the default toolchain)
def firmware_toolchain() -> tuple[str, list[str], list[str]]:
    try:
        tc = tomllib.loads((FIRMWARE / "rust-toolchain.toml").read_text())["toolchain"]
    except (OSError, KeyError, tomllib.TOMLDecodeError):
        tc = {}
    components = sorted(set(tc.get("components", [])) | {"rustfmt", "clippy"})
    return tc.get("channel", "stable"), list(tc.get("targets", [])), components


def build_tools_step(p: Platform) -> Step:
    if p.kind == "windows":

        def check() -> Status:
            vswhere = Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"))
            vswhere = vswhere / "Microsoft Visual Studio" / "Installer" / "vswhere.exe"
            missing = [t for t in ("git",) if not which(t)]
            vs = None
            if vswhere.exists():
                vs = output(
                    str(vswhere), "-products", "*", "-latest", "-property", "installationPath",
                    "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64",
                )  # fmt: skip
            if not (vs and vs.strip()):
                missing.insert(0, "MSVC build tools (C++ linker)")
            return Status(not missing, "missing: " + ", ".join(missing) if missing else "MSVC, git")

        return Step(
            "build tools",
            check,
            root_commands=[
                (
                    "winget install --id Microsoft.VisualStudio.2022.BuildTools -e --override "
                    '"--passive --wait --add Microsoft.VisualStudio.Workload.VCTools --includeRecommended"'
                ),
                "winget install --id Git.Git -e",
            ],
            prerequisite=True,
        )

    tools = ["cc", "git"] + (["curl"] if p.kind != "macos" else [])

    def check() -> Status:
        missing = [{"cc": "C compiler (cc)"}.get(t, t) for t in tools if not which(t)]
        return Status(
            not missing, "missing: " + ", ".join(missing) if missing else "C compiler, " + ", ".join(tools[1:])
        )

    commands, manual = [], ""
    if p.kind == "arch":
        commands = [f"{p.sudo}pacman -S --needed --noconfirm base-devel git curl"]
    elif p.kind == "debian":
        commands = [
            f"{p.sudo}apt-get update",
            f"{p.sudo}apt-get install -y build-essential git curl ca-certificates",
        ]
    elif p.kind == "macos":
        commands = ["xcode-select --install"]
    else:
        manual = "install a C compiler and linker (gcc or clang), git and curl with your distribution's packages"
    return Step("build tools", check, root_commands=commands, manual=manual, prerequisite=True)


def rustup_step(p: Platform) -> Step:
    def check() -> Status:
        st = version_of("rustup")
        if not st.ok and which("cargo"):
            return Status(False, f"cargo without rustup at {which('cargo')}: remove the distribution's Rust first")
        return st

    def install() -> bool:
        if which("cargo") and not which("rustup"):
            hint = " (`sudo pacman -R rust`, then `just setup` again)" if p.kind == "arch" else ""
            print(S.bad(f"  a Rust without rustup is installed ({which('cargo')}): remove it first{hint}"))
            return False
        if p.kind == "windows":
            ok = run(["winget", "install", "--id", "Rustlang.Rustup", "-e",
                      "--accept-source-agreements", "--accept-package-agreements"])  # fmt: skip
        else:
            script = download(RUSTUP_INSTALLER, ".sh")
            ok = run(["sh", str(script), "-y", "--profile", "minimal", "--default-toolchain", "stable"])
            script.unlink(missing_ok=True)
        add_cargo_bin_to_path()
        return ok and which("rustup") is not None

    remote = "" if p.kind == "windows" else f"runs rustup's installer script from {RUSTUP_INSTALLER}"
    return Step("rustup", check, install, remote=remote)


def toolchain_step() -> Step:
    channel, targets, components = firmware_toolchain()

    def missing() -> list[str]:
        if not which("rustup"):
            return ["rustup"]
        if output("rustup", "run", channel, "rustc", "--version") is None:
            return [f"toolchain {channel}"]
        have_t = (output("rustup", "target", "list", "--installed", "--toolchain", channel) or "").split()
        have_c = output("rustup", "component", "list", "--installed", "--toolchain", channel) or ""
        out = [t for t in targets if t not in have_t]
        out += [c for c in components if not any(line.startswith(c + "-") for line in have_c.split())]
        if output("rustup", "default") is None or "no default" in (output("rustup", "default") or ""):
            out.append("default toolchain")
        return out

    def check() -> Status:
        m = missing()
        return Status(not m, "missing: " + ", ".join(m) if m else f"{channel}, " + ", ".join(targets + components))

    def install() -> bool:
        ok = run(["rustup", "toolchain", "install", channel, "--profile", "minimal"])
        if ok and targets:
            ok = run(["rustup", "target", "add", "--toolchain", channel, *targets])
        if ok:
            ok = run(["rustup", "component", "add", "--toolchain", channel, *components])
        if ok and "default toolchain" in missing():
            ok = run(["rustup", "default", channel])
        return ok

    return Step("Rust toolchain", check, install)


def probe_rs_step(p: Platform) -> Step:
    def install() -> bool:
        if p.kind == "windows":
            return run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command",
                        f"irm {PROBE_RS_INSTALLER}.ps1 | iex"])  # fmt: skip
        script = download(PROBE_RS_INSTALLER + ".sh", ".sh")
        ok = run(["sh", str(script)])
        script.unlink(missing_ok=True)
        add_cargo_bin_to_path()
        return ok

    if p.kind == "windows":
        remote = (
            f"runs probe-rs's PowerShell installer from {PROBE_RS_INSTALLER}.ps1 (irm | iex, ExecutionPolicy Bypass)"
        )
    else:
        remote = f"runs probe-rs's installer script from {PROBE_RS_INSTALLER}.sh"
    return Step("probe-rs", lambda: version_of("probe-rs"), install, remote=remote)


def cargo_tool_step(binary: str, what: str, args: list[str]) -> Step:
    def install() -> bool:
        print(S.dim(f"  {binary}: {what}"))
        return run(["cargo", "install", "--locked", *args])

    return Step(binary, lambda: version_of(binary), install)


def probe_access_step(p: Platform) -> Step | None:
    if p.kind == "windows":
        if not WINDOWS_DRIVER:
            return None
        match, how = WINDOWS_DRIVER

        def check() -> Status:
            ok = match in (output("pnputil", "/enum-drivers") or "").lower()
            return Status(ok, f"{PROBE[0]} driver installed" if ok else f"{PROBE[0]} driver not found")

        return Step(f"{PROBE[0]} driver", check, manual=how)
    if p.kind == "macos":
        return None
    name, needles = PROBE

    def check() -> Status:
        for d in UDEV_DIRS:
            for rules in sorted(d.glob("*.rules")) if d.is_dir() else []:
                text = rules.read_text(errors="replace").lower()
                if all(n in text for n in needles):
                    return Status(True, f"{name} rule in {rules}")
        return Status(False, f"no udev rule for the {name}: only root could open the probe")

    return Step(
        "probe access (udev)",
        check,
        root_commands=[
            f"{p.sudo}mkdir -p /etc/udev/rules.d",
            f"curl -fsSL {PROBE_RS_UDEV} | {p.sudo}tee /etc/udev/rules.d/69-probe-rs.rules >/dev/null",
            f"{p.sudo}udevadm control --reload && {p.sudo}udevadm trigger || true",
        ],
        remote=f"writes probe-rs's udev rules from {PROBE_RS_UDEV} as root",
    )


def prerequisite_step(tool: str, how: str) -> Step:
    return Step(tool, lambda: version_of(tool), manual=how)


def git_hooks_step() -> Step:
    hooks = [sys.executable, str(ROOT / "scripts" / "hooks.py")]

    def check() -> Status:
        out = subprocess.run([*hooks, "--check"], capture_output=True, text=True, check=False)
        return Status(out.returncode == 0, out.stdout.strip())

    return Step("git hooks", check, lambda: run(hooks))


def steps_for(p: Platform, probe: bool, skip: set[str]) -> list[Step]:
    win = p.kind == "windows"
    steps = [
        prerequisite_step(
            "just", "winget install --id Casey.Just -e" if win else "https://just.systems/man/en/packages.html"
        ),
        prerequisite_step(
            "uv",
            "winget install --id astral-sh.uv -e" if win else "https://docs.astral.sh/uv/getting-started/installation/",
        ),
        build_tools_step(p),
        rustup_step(p),
        toolchain_step(),
        probe_rs_step(p),
        *(cargo_tool_step(*t) for t in CARGO_TOOLS),
        git_hooks_step(),
    ]
    access = probe_access_step(p) if probe else None
    if access:
        steps.append(access)
    return [st for st in steps if st.name not in skip]


# ------------------------------------------------------------------------------------------------------------------ main


def line(step: Step, st: Status) -> None:
    mark = S.ok("✓") if st.ok else S.bad("✗")
    print(f"{mark} {step.name:<22} {S.dim(st.detail) if st.ok else st.detail}")


def run_root_commands(step: Step) -> bool:
    shell = ["powershell", "-NoProfile", "-Command"] if os.name == "nt" else ["sh", "-c"]
    for cmd in step.root_commands:
        print(S.dim(f"  # {cmd}"), flush=True)
        if subprocess.run([*shell, cmd], check=False).returncode != 0:
            return False
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only report what is missing; exit 1 if anything is")
    ap.add_argument(
        "--root",
        action="store_true",
        help="also run the steps that need root or an administrator (through sudo, each shown first)",
    )
    ap.add_argument(
        "--no-probe", action="store_true", help="leave out the probe's udev rule or driver (CI, a build server)"
    )
    ap.add_argument("--skip", action="append", default=[], metavar="TOOL", help="leave this step out (repeatable)")
    args = ap.parse_args()

    p = detect_platform()
    add_cargo_bin_to_path()
    print(S.bold(f"Setting up {ROOT.name} on {p.name}") if not args.check else S.bold(f"Checking {p.name}"))
    steps = steps_for(p, probe=not args.no_probe, skip=set(args.skip))
    for name in args.skip:
        print(S.warn("-") + f" {name:<22} skipped (--skip)")

    if args.check:
        missing = 0
        for step in steps:
            st = step.check()
            line(step, st)
            missing += not st.ok
        if missing:
            print(S.bad(f"\n{missing} missing:") + " `just setup` installs them (root steps are printed)")
        return 1 if missing else 0

    # The plan: what is missing and how each gets there, remote scripts named, before anything changes
    todo = [step for step in steps if not step.check().ok]
    if todo:
        print(S.bold("Plan:"))
        for step in todo:
            how = "install" if step.install else ("run as root (--root)" if args.root and step.root_commands else "you")
            print(f"  {step.name:<22} {how}" + (f"; {step.remote}" if step.remote else ""))
        print()

    for_person: list[tuple[Step, Status]] = []
    failed: list[str] = []
    for step in steps:
        st = step.check()
        if st.ok:
            line(step, st)
            continue
        if not step.install and not (step.root_commands and args.root):
            line(step, st)
            for_person.append((step, st))
            if step.prerequisite:
                print(S.dim("  (the other steps need it: they follow once it is there)"))
                break
            continue
        print(S.warn("→") + f" {step.name:<22} {st.detail}", flush=True)
        t0 = time.monotonic()
        ok = step.install() if step.install else run_root_commands(step)
        st = step.check() if ok else Status(False, "failed")
        took = S.dim(f"({time.monotonic() - t0:.0f} s)")
        print((S.ok("✓") if st.ok else S.bad("✗")) + f" {step.name:<22} {st.detail} {took}", flush=True)
        if not st.ok:
            failed.append(step.name)
            if step.prerequisite:
                break

    if for_person:
        print(S.bold("\nThese need you (root or administrator, or a download):"))
        for step, st in for_person:
            print(f"\n  {S.bold(step.name)}: {st.detail}")
            if step.remote:
                print(f"    ({step.remote})")
            for cmd in step.root_commands:
                print(f"    {cmd}")
            if step.manual:
                print(f"    {step.manual}")
        print("\nThen run `just setup` again (or `just setup --root` to have it run them).")
    if failed:
        print(S.bad("\nfailed: " + ", ".join(failed)))
    if not for_person and not failed:
        print(S.ok("\nAll set.") + " Open a new shell if rustup was just installed (it adds ~/.cargo/bin to PATH).")
    return 1 if failed or for_person else 0


if __name__ == "__main__":
    sys.exit(main())
